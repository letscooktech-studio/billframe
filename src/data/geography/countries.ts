export class GeographyService {
  public static getAllCountries(): CountryMetadata[] {
    return COUNTRIES.filter((c) => c.active);
  }

  public static getCountryByIso2(iso2: string): CountryMetadata | undefined {
    if (!iso2) return undefined;
    const clean = iso2.trim().toUpperCase();
    return COUNTRIES.find((c) => c.iso2 === clean);
  }

  /**
   * Searches countries by name, ISO-2, ISO-3, or calling code.
   */
  public static searchCountries(query: string): CountryMetadata[] {
    const clean = (query || '').trim().toLowerCase();
    if (!clean) return this.getAllCountries();

    return this.getAllCountries().filter((c) => {
      if (c.name.toLowerCase().includes(clean)) return true;
      if (c.iso2.toLowerCase().includes(clean)) return true;
      if (c.iso3.toLowerCase().includes(clean)) return true;
      if (c.callingCode.replace('+', '').includes(clean.replace('+', ''))) return true;
      if (c.currencyCode.toLowerCase().includes(clean)) return true;
      return false;
    });
  }

  public static getDefaultCurrency(countryIso2: string): string {
    const meta = this.getCountryByIso2(countryIso2);
    return meta?.currencyCode || 'USD';
  }

  public static getSubdivisionLabel(countryIso2: string): string {
    const meta = this.getCountryByIso2(countryIso2);
    if (!meta) return 'State / Province / Region';
    return meta.subdivisionType;
  }
}
